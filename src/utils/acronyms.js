export function getAcronymExplanation(text, lang = "en") {
  const glossary = acronymGlossary[lang] || acronymGlossary.en;
  
  // Check direct matches or acronyms inside the text
  const acronyms = ["AMT", "HUF", "LLP", "AOP", "BOI", "AJP", "ERI", "TRP", "ITR", "PAN", "TAN", "TDS", "TCS", "DTAA", "MAT", "DSC"];
  const matches = [];
  
  for (const acr of acronyms) {
    // Match word boundaries or inside slashes/parentheses
    const regex = new RegExp(`(^|[/()\\s-])${acr}([/()\\s-]|$)`, "i");
    if (regex.test(text)) {
      if (glossary[acr]) {
        matches.push(glossary[acr]);
      }
    }
  }
  
  return matches.length > 0 ? matches.join("\n\n") : null;
}
